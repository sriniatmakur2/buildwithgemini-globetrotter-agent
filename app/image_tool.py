import re
import uuid
from typing import Optional
from google import genai
from google.genai import types
from google.cloud import storage
from google.adk.tools import ToolContext

PROJECT_ID = "qwiklabs-gcp-02-88a55e82ef51"
BUCKET_NAME = "globetrotter-media-88a55e82ef51"
LOCATION = "global"
MODEL_NAME = "gemini-3.1-flash-lite-image"

async def generate_travel_poster(
    prompt: str,
    destination_name: Optional[str] = None,
    tool_context: Optional[ToolContext] = None
) -> str:
    """Generate a scenic AI travel poster or postcard image for a destination using Gemini image generation model.

    Args:
        prompt: Detailed visual prompt describing the image to generate (e.g., 'A sunset view of Fushimi Inari torii gates in Kyoto with cherry blossoms').
        destination_name: Optional name of the travel destination (e.g. 'Kyoto', 'Santorini', 'Bali').

    Returns:
        The public HTTPS URL of the generated poster stored in Google Cloud Storage.
    """
    try:
        # 1. Generate image using gemini-3.1-flash-lite-image in global location
        client = genai.Client(vertexai=True, project=PROJECT_ID, location=LOCATION)
        
        full_prompt = (
            f"A beautiful high quality artistic travel poster of {destination_name}: {prompt}"
            if destination_name
            else prompt
        )
        
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=full_prompt,
            config=types.GenerateContentConfig(response_modalities=["IMAGE"])
        )
        
        if not response.candidates or not response.candidates[0].content.parts:
            return "Error: No image content generated by model."
            
        part = response.candidates[0].content.parts[0]
        if not part.inline_data or not part.inline_data.data:
            return "Error: Inline image data missing in model response."
            
        image_bytes = part.inline_data.data
        mime_type = part.inline_data.mime_type or "image/jpeg"
        ext = "png" if "png" in mime_type.lower() else "jpg"
        
        raw_slug = (destination_name or "travel").lower().replace(" ", "_")
        clean_slug = re.sub(r'[^a-zA-Z0-9_-]', '', raw_slug)
        filename = f"poster_{clean_slug}_{uuid.uuid4().hex[:8]}.{ext}"
        
        # (1) Save artifact for Playground Artifacts panel if tool_context is provided
        if tool_context:
            artifact_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
            await tool_context.save_artifact(filename=filename, artifact=artifact_part)
            
        # (2) Upload image bytes to public Cloud Storage bucket
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(image_bytes, content_type=mime_type)
        
        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"
        return f"Successfully generated travel poster for '{destination_name or 'destination'}'. Public Image URL: {public_url}"
        
    except Exception as e:
        return f"Error generating travel poster: {str(e)}"
